@dataclass(frozen=True)
class Example:
    key: str                 # 例題の番号（A-1 など）
    group: str               # 章
    title: str
    lesson: str              # この例題で見てほしいところ
    spec: dict[str, Any]     # make_context に渡す内容
    han: int | None          # 期待値（和了れない例は None）
    fu: int | None
    say: str | None          # 卓での点数の申告
    rules: Rules = field(default=DEFAULT_RULES)

    @property
    def label(self) -> str:
        return f"{self.key} {self.title}"

    def context(self) -> WinContext:
        return make_context(**self.spec)


